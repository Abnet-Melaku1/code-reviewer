import json

from codereviewer.providers.base import LlmProvider
from codereviewer.schemas.enums import CitationKind, DiffSide, Severity
from codereviewer.schemas.models import Citation, DiffHunk, RetrievedContext, ReviewComment


def load_prompt_template() -> tuple[str, str]:
    """Load and parse the system and user prompt templates."""
    import importlib.resources

    ref = importlib.resources.files("codereviewer.reviewer.prompts") / "style_review.txt"
    content = ref.read_text(encoding="utf-8")

    parts = content.split("User Prompt:")
    system_part = parts[0].replace("System Prompt:", "").strip()
    user_part = parts[1].strip() if len(parts) > 1 else ""
    return system_part, user_part


class StyleAnalyzer:
    """Style and conventions analyzer using LLM completions."""

    name: str = "style_analyzer"

    def __init__(self, provider: LlmProvider):
        self.provider = provider

    def applies_to(self, language: str) -> bool:
        """Style rules and conventions are applicable to all languages."""
        return True

    async def analyze(self, hunk: DiffHunk, context: RetrievedContext) -> list[ReviewComment]:
        """Analyze a diff hunk against grounding chunks and conventions."""
        system_tmpl, user_tmpl = load_prompt_template()

        # Format retrieved chunks
        chunks_str = ""
        for idx, chunk in enumerate(context.chunks):
            chunks_str += (
                f"- Chunk #{idx + 1} (ID: {chunk.id}, Symbol: {chunk.symbol_name or 'unnamed'}): "
                f"Lines {chunk.start_line}-{chunk.end_line} in {hunk.file_path}\n"
                f"```\n{chunk.content}\n```\n"
            )

        # Format conventions
        convs_str = ""
        for conv in context.conventions:
            convs_str += f"- Title: {conv.title}\n  Description: {conv.description}\n"
            if conv.example_code:
                convs_str += f"  Example:\n  ```\n  {conv.example_code}\n  ```\n"

        # Format user prompt
        user_prompt = user_tmpl.format(
            file_path=hunk.file_path,
            start_line=hunk.start_line,
            end_line=hunk.end_line,
            diff_content=hunk.content,
            retrieved_chunks=chunks_str or "No similar context chunks found.",
            retrieved_conventions=convs_str or "No codebase style conventions found.",
        )

        response_str = await self.provider.generate_response(system_tmpl, user_prompt)

        # Clean markdown wrappers if generated by model
        cleaned = response_str.strip()
        if cleaned.startswith("```"):
            lines = cleaned.splitlines()
            if lines[0].startswith("```"):
                lines = lines[1:]
            if lines and lines[-1].startswith("```"):
                lines = lines[:-1]
            cleaned = "\n".join(lines).strip()

        try:
            raw_comments = json.loads(cleaned)
        except Exception:
            return []

        comments = []
        for raw in raw_comments:
            try:
                # Map citations
                citations = []

                # Baseline: cite the diff hunk itself
                citations.append(
                    Citation(
                        kind=CitationKind.diff_hunk,
                        diff_ref=f"{hunk.file_path}#L{hunk.start_line}-{hunk.end_line}",
                    )
                )

                # Map chunks by ID
                for chunk_id in raw.get("citation_ids", []):
                    matched_chunk = next((c for c in context.chunks if c.id == chunk_id), None)
                    if matched_chunk and matched_chunk.id is not None:
                        citations.append(
                            Citation(
                                kind=CitationKind.code_chunk,
                                code_chunk_id=matched_chunk.id,
                            )
                        )

                # Map conventions by title
                for title in raw.get("citation_conventions", []):
                    matched_conv = next(
                        (c for c in context.conventions if c.title == title),
                        None,
                    )
                    if matched_conv and matched_conv.id is not None:
                        citations.append(
                            Citation(
                                kind=CitationKind.convention,
                                convention_id=matched_conv.id,
                            )
                        )

                comments.append(
                    ReviewComment(
                        file_path=raw["file_path"],
                        line=raw["line"],
                        side=DiffSide(raw["side"]),
                        severity=Severity(raw["severity"]),
                        body=raw["body"],
                        suggested_patch=raw.get("suggested_patch"),
                        citations=citations,
                    )
                )
            except Exception:
                continue

        return comments


def register_default_analyzers(provider: LlmProvider) -> None:
    """Register all default review analyzers in the registry."""
    from codereviewer.reviewer.base import register_analyzer

    register_analyzer(StyleAnalyzer(provider))
